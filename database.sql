-- ---------------------------------------------------------------------
-- 1. TABLAS
-- ---------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name varchar(100) not null,
  role varchar(20) not null default 'usuario',
  created_at timestamptz not null default now()
);

create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title varchar(150) not null,
  description text not null,
  category varchar(50) not null,
  priority varchar(20) not null default 'Media',
  status varchar(20) not null default 'Abierto',
  technician_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.tickets(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  action varchar(30) not null,
  old_status varchar(20),
  new_status varchar(20),
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 2. RESTRICCIONES (CHECK) [BD-3]
-- Se eliminan y se vuelven a crear para que la lista oficial sea la misma
-- en todas las bases, incluso si un estudiante agregó valores distintos.
-- Las listas DEBEN coincidir con src/types.ts.
-- ---------------------------------------------------------------------

-- Normaliza datos que no cumplen la lista oficial (solo afecta bases v2 modificadas).
update public.profiles set role = 'usuario' where role not in ('usuario', 'tecnico', 'admin');
update public.tickets  set category = 'Otro' where category not in ('Acceso', 'Hardware', 'Software', 'Red', 'Otro');

alter table public.profiles drop constraint if exists profiles_full_name_check;
alter table public.profiles drop constraint if exists profiles_role_check;
alter table public.profiles
  add constraint profiles_full_name_check check (char_length(trim(full_name)) between 3 and 100),
  add constraint profiles_role_check check (role in ('usuario', 'tecnico', 'admin'));

alter table public.tickets drop constraint if exists tickets_title_check;
alter table public.tickets drop constraint if exists tickets_description_check;
alter table public.tickets drop constraint if exists tickets_category_check;
alter table public.tickets drop constraint if exists tickets_priority_check;
alter table public.tickets drop constraint if exists tickets_status_check;
alter table public.tickets
  add constraint tickets_title_check check (char_length(trim(title)) between 5 and 150),
  add constraint tickets_description_check check (char_length(trim(description)) between 10 and 1500),
  add constraint tickets_category_check check (category in ('Acceso', 'Hardware', 'Software', 'Red', 'Otro')),
  add constraint tickets_priority_check check (priority in ('Baja', 'Media', 'Alta', 'Crítica')),
  add constraint tickets_status_check check (status in ('Abierto', 'En proceso', 'Resuelto', 'Cerrado'));

alter table public.audit_logs drop constraint if exists audit_logs_action_check;
alter table public.audit_logs
  add constraint audit_logs_action_check check (action in ('STATUS_CHANGE', 'ASSIGN'));

create index if not exists idx_tickets_user_id on public.tickets(user_id);
create index if not exists idx_tickets_status on public.tickets(status);
create index if not exists idx_tickets_technician_id on public.tickets(technician_id);
create index if not exists idx_audit_ticket_id on public.audit_logs(ticket_id);

-- ---------------------------------------------------------------------
-- 3. PERFIL AUTOMÁTICO AL REGISTRARSE [BD-1]
-- El rol SIEMPRE inicia como 'usuario'. Nunca se toma de los metadatos
-- enviados por el navegador (el usuario podría enviar role=admin).
-- ---------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  v_name text := trim(coalesce(new.raw_user_meta_data ->> 'full_name', ''));
begin
  if char_length(v_name) < 3 then
    v_name := 'Usuario ' || split_part(new.email, '@', 1);
  end if;
  insert into public.profiles (id, full_name, role)
  values (new.id, left(v_name, 100), 'usuario')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

-- [BD-2] Usuarios que se registraron cuando el trigger fallaba o no existía.
insert into public.profiles (id, full_name, role)
select u.id,
       left(case when char_length(trim(coalesce(u.raw_user_meta_data ->> 'full_name', ''))) >= 3
                 then trim(u.raw_user_meta_data ->> 'full_name')
                 else 'Usuario ' || split_part(u.email, '@', 1) end, 100),
       'usuario'
from auth.users u
where not exists (select 1 from public.profiles p where p.id = u.id);

-- ---------------------------------------------------------------------
-- 4. FUNCIONES DE ROL
-- ---------------------------------------------------------------------
create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and role in ('tecnico','admin')); $$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin'); $$;

-- ---------------------------------------------------------------------
-- 5. REGLAS DE ACTUALIZACIÓN DE TICKETS [BD-5]
-- Flujo permitido para técnico:
--   Abierto    -> En proceso | Cerrado
--   En proceso -> Resuelto
--   Resuelto   -> Cerrado | En proceso (reabrir)
--   Cerrado    -> (solo admin puede reabrir)
-- El administrador puede hacer cualquier cambio.
-- Cambios ejecutados desde SQL Editor (sin usuario de la app) no se limitan.
-- ---------------------------------------------------------------------
create or replace function public.enforce_ticket_update()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_admin boolean := public.is_admin();
begin
  if v_uid is null then
    return new;
  end if;

  if new.status is distinct from old.status and not v_admin then
    if not (
         (old.status = 'Abierto'    and new.status in ('En proceso', 'Cerrado'))
      or (old.status = 'En proceso' and new.status = 'Resuelto')
      or (old.status = 'Resuelto'   and new.status in ('En proceso', 'Cerrado'))
    ) then
      raise exception 'Cambio de estado no permitido: % -> %', old.status, new.status
        using hint = 'Revise el flujo: Abierto > En proceso > Resuelto > Cerrado.';
    end if;
  end if;

  -- Al tomar un ticket se asigna al técnico que lo atiende.
  if new.status = 'En proceso' and new.technician_id is null then
    new.technician_id := v_uid;
  end if;

  if new.technician_id is distinct from old.technician_id and new.technician_id is not null then
    if not v_admin and new.technician_id <> v_uid then
      raise exception 'Un técnico solo puede asignarse tickets a sí mismo.';
    end if;
    if not exists (select 1 from public.profiles where id = new.technician_id and role in ('tecnico', 'admin')) then
      raise exception 'El usuario asignado no es técnico ni administrador.';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_tickets_enforce_update on public.tickets;
create trigger trg_tickets_enforce_update before update on public.tickets
for each row execute procedure public.enforce_ticket_update();

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = public
as $$ begin new.updated_at = now(); return new; end; $$;

drop trigger if exists trg_tickets_updated_at on public.tickets;
create trigger trg_tickets_updated_at before update on public.tickets
for each row execute procedure public.set_updated_at();

-- ---------------------------------------------------------------------
-- 6. AUDITORÍA [BD-6]
-- ---------------------------------------------------------------------
create or replace function public.log_ticket_status_change()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if new.status is distinct from old.status then
    insert into public.audit_logs(ticket_id, actor_id, action, old_status, new_status)
    values (new.id, auth.uid(), 'STATUS_CHANGE', old.status, new.status);
  end if;
  if new.technician_id is distinct from old.technician_id then
    insert into public.audit_logs(ticket_id, actor_id, action, old_status, new_status)
    values (new.id, auth.uid(), 'ASSIGN', old.status, new.status);
  end if;
  return new;
end;
$$;

drop trigger if exists trg_audit_ticket_status on public.tickets;
create trigger trg_audit_ticket_status after update on public.tickets
for each row execute procedure public.log_ticket_status_change();

-- ---------------------------------------------------------------------
-- 7. ROW LEVEL SECURITY
-- ---------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.tickets enable row level security;
alter table public.audit_logs enable row level security;

-- [BD-7] FORCE RLS aplica RLS incluso al propietario de las tablas.
-- Solo se activa si el usuario que ejecuta el script tiene BYPASSRLS (caso Supabase:
-- postgres). Si no lo tiene (caso Neon: neondb_owner), FORCE bloquearía al trigger
-- que crea perfiles ("new row violates row-level security policy for table profiles")
-- y los UPDATE del SQL Editor afectarían 0 filas sin avisar.
-- En ambos casos RLS sigue activo para los roles anon y authenticated.
do $$
begin
  if (select rolbypassrls or rolsuper from pg_roles where rolname = current_user) then
    alter table public.profiles force row level security;
    alter table public.tickets force row level security;
    alter table public.audit_logs force row level security;
  else
    alter table public.profiles no force row level security;
    alter table public.tickets no force row level security;
    alter table public.audit_logs no force row level security;
    raise notice 'Usuario % sin BYPASSRLS (ej. Neon): FORCE RLS no se aplica al propietario.', current_user;
  end if;
end $$;

drop policy if exists profile_select_own_or_staff on public.profiles;
drop policy if exists ticket_select_own_or_staff on public.tickets;
drop policy if exists ticket_insert_own on public.tickets;
drop policy if exists ticket_update_staff_only on public.tickets;
drop policy if exists audit_select_admin_only on public.audit_logs;

create policy profile_select_own_or_staff on public.profiles
for select to authenticated using (id = auth.uid() or public.is_staff());

create policy ticket_select_own_or_staff on public.tickets
for select to authenticated using (user_id = auth.uid() or public.is_staff());

create policy ticket_insert_own on public.tickets
for insert to authenticated with check (
  user_id = auth.uid()
  and status = 'Abierto'
  and technician_id is null
);

-- Un usuario normal NO puede modificar tickets desde la Data API.
-- Solo técnico/admin puede actualizar. La seguridad se aplica en PostgreSQL.
create policy ticket_update_staff_only on public.tickets
for update to authenticated using (public.is_staff()) with check (public.is_staff());

create policy audit_select_admin_only on public.audit_logs
for select to authenticated using (public.is_admin());

-- ---------------------------------------------------------------------
-- 8. PRIVILEGIO MÍNIMO [BD-4]
-- No existe política ni permiso de INSERT/UPDATE en profiles: el perfil
-- solo lo crea el trigger y el rol solo se cambia desde SQL Editor.
-- ---------------------------------------------------------------------
revoke all on table public.profiles, public.tickets, public.audit_logs from anon;
revoke all on table public.profiles, public.tickets, public.audit_logs from authenticated;

grant select on table public.profiles to authenticated;
grant select on table public.tickets to authenticated;
grant insert (user_id, title, description, category, priority) on table public.tickets to authenticated;
grant update (status, technician_id) on table public.tickets to authenticated;
grant select on table public.audit_logs to authenticated;
grant usage, select on sequence public.tickets_id_seq to authenticated;

-- Las funciones internas no se exponen como RPC a usuarios anónimos.
revoke execute on function public.handle_new_user() from public, anon, authenticated;
revoke execute on function public.enforce_ticket_update() from public, anon, authenticated;
revoke execute on function public.log_ticket_status_change() from public, anon, authenticated;

