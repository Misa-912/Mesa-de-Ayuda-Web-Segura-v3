-- Ejecutar completo en Supabase > SQL Editor.
-- Seguridad real: autenticación + RLS + privilegio mínimo + restricciones.
--
-- Este script se puede ejecutar de nuevo sobre una base creada con la v2:
-- corrige restricciones, funciones, políticas y permisos sin borrar datos.
--
-- Cambios v3 respecto a v2:
--  [BD-1] handle_new_user ya no falla con correos cortos (ej. ab@correo.com).
--  [BD-2] Se crean perfiles faltantes de usuarios registrados con la v2.
--  [BD-3] Restricciones con nombre fijo para poder recrearlas.
--  [BD-4] El técnico solo puede modificar status y technician_id (no título,
--         descripción ni propietario).
--  [BD-5] Cambio controlado de estados (flujo permitido) y asignación
--         automática del técnico al pasar a "En proceso".
--  [BD-6] audit_logs con acciones válidas y registro de asignación.
